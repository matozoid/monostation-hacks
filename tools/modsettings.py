#!/usr/bin/env python3
"""Mod settings (docs/mod-settings.md): the [[setting]] tables of overlay.toml, the
description table and header that fwsrc.py generate writes for the overlays/settings
overlay, and the store in external flash at 0x7FF000.

    python3 tools/modsettings.py list overlays/drive ...          # the settings of overlays
    python3 tools/modsettings.py store OUT.bin [ID=VALUE ...]     # a store subsector
    python3 tools/modsettings.py show STORE.bin                   # decode a store
"""

import re
import struct
import sys
import tomllib
import zlib
from collections import namedtuple
from pathlib import Path

KINDS = {"flag": 0, "number": 1, "slider": 2, "enum": 3, "text": 4}
WHEN = {"live": 0, "boot": 1}
NAME_MAX = 24           # characters of a name, a group or an enum label
TEXT_MAX = 32           # longest text value
ENUM_MAX = 16           # labels of an enum

STORE_ADDRESS = 0x7FF000
STORE_BYTES = 0x1000
STORE_MAGIC = b"MODS"
STORE_VERSION = 1
STORE_HEADER = 8
FORMAT_VERSION = 1      # of the 0x7C descriptions (op 3)

SETTINGS_OVERLAY = "settings"   # the overlay that holds mod_setting() and the SysEx
TABLE_SOURCE = "zz_overlay__settings_table.c"   # in the generated tree, sorted with overlays
HEADER = "mod_settings.h"
GENERATED_C = "/* Generated by tools/fwsrc.py from the overlays' [[setting]] tables. */"

Setting = namedtuple("Setting", "id name kind when min max default labels group")

KEYS = {"id", "name", "kind", "when", "min", "max", "default", "labels"}


def _ascii(value, what, longest):
    if not isinstance(value, str) or not value or len(value) > longest \
            or any(not 0x20 <= ord(c) < 0x7F for c in value):
        raise ValueError(f"{what} must be 1 to {longest} printable ASCII characters")
    return value


def parse(table, group, where):
    """One [[setting]] table of the overlay named `group`."""
    unknown = set(table) - KEYS
    if unknown:
        raise ValueError(f"{where}: unknown keys {sorted(unknown)}")
    sid = table.get("id")
    if not isinstance(sid, int) or not 1 <= sid <= 0xFFFF:
        raise ValueError(f"{where}: id must be 0x0001 to 0xFFFF")
    where = f"{where} (id {sid:#06x})"
    name = _ascii(table.get("name"), f"{where}: name", NAME_MAX)
    kind = table.get("kind")
    if kind not in KINDS:
        raise ValueError(f"{where}: kind must be one of {', '.join(KINDS)}")
    when = table.get("when", "live")
    if when not in WHEN:
        raise ValueError(f"{where}: when must be live or boot")
    allowed = {"flag": {"default"}, "number": {"min", "max", "default"},
               "slider": {"min", "max", "default"}, "enum": {"labels", "default"},
               "text": {"max", "default"}}[kind]
    extra = set(table) - allowed - {"id", "name", "kind", "when"}
    if extra:
        raise ValueError(f"{where}: a {kind} has no {', '.join(sorted(extra))}")
    default = table.get("default", "" if kind == "text" else 0)
    labels = ()
    if kind == "flag":
        lo, hi = 0, 1
    elif kind in ("number", "slider"):
        lo, hi = table.get("min"), table.get("max")
        if not all(isinstance(v, int) and -0x8000 <= v <= 0x7FFF for v in (lo, hi)) or lo > hi:
            raise ValueError(f"{where}: needs min <= max, both signed 16-bit")
    elif kind == "enum":
        labels = table.get("labels")
        if not isinstance(labels, list) or not 2 <= len(labels) <= ENUM_MAX:
            raise ValueError(f"{where}: labels must list 2 to {ENUM_MAX} names")
        labels = tuple(_ascii(l, f"{where}: a label", NAME_MAX) for l in labels)
        lo, hi = 0, len(labels) - 1
    else:
        lo, hi = 0, table.get("max")
        if not isinstance(hi, int) or not 1 <= hi <= TEXT_MAX:
            raise ValueError(f"{where}: max (the longest text) must be 1 to {TEXT_MAX}")
        if not isinstance(default, str) or len(default) > hi \
                or any(not 0x20 <= ord(c) < 0x7F for c in default):
            raise ValueError(f"{where}: default must be printable ASCII, at most max long")
    if kind != "text" and (not isinstance(default, int) or isinstance(default, bool)
                           or not lo <= default <= hi):
        raise ValueError(f"{where}: default must be between {lo} and {hi}")
    return Setting(sid, name, kind, when, lo, hi, default, labels, group)


def from_toml(tables, group, path):
    """The [[setting]] list of an overlay.toml (`tables`: what tomllib gave for it)."""
    if not isinstance(tables, list):
        raise ValueError(f"{path}: setting must be a list of tables ([[setting]])")
    _ascii(group, f"{path}: the overlay name (the settings' group)", NAME_MAX)
    return [parse(t, group, f"{path}: setting {i + 1}") for i, t in enumerate(tables)]


def macro(name):
    """SETTING_<NAME>: "Overdrive amount" -> SETTING_OVERDRIVE_AMOUNT."""
    return "SETTING_" + re.sub(r"[^A-Z0-9]+", "_", name.upper()).strip("_")


def check(settings):
    """Ids and header names must be unique across the build."""
    seen, names = {}, {}
    for s in settings:
        if s.id in seen:
            raise ValueError(f"setting id {s.id:#06x} is in {seen[s.id]} and {s.group}")
        seen[s.id] = s.group
        m = macro(s.name)
        if m in names:
            raise ValueError(f"settings {names[m]!r} and {s.name!r} both give {m}")
        names[m] = s.name


def groups(settings):
    out = []
    for s in settings:
        if s.group not in out:
            out.append(s.group)
    return out


def text_bytes(settings):
    return sum(s.max + 1 for s in settings if s.kind == "text")


def _c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header(settings):
    lines = [GENERATED_C, "#ifndef MOD_SETTINGS_H", "#define MOD_SETTINGS_H", "",
             "#include <settings.h>", "",
             f"#define MOD_SETTING_COUNT {len(settings)}",
             f"#define MOD_GROUP_COUNT {len(groups(settings))}",
             f"#define MOD_TEXT_BYTES {text_bytes(settings)}", ""]
    lines += [f"#define {macro(s.name)} {s.id:#06x}u /* {s.group}: {s.name} */" for s in settings]
    return "\n".join(lines + ["", "#endif", ""])


def table(settings):
    """C source of the description table (const, in flash after the image)."""
    names = groups(settings)
    lines = [GENERATED_C, f"#include <{HEADER}>", ""]
    for i, s in enumerate(settings):
        if s.labels:
            lines.append(f"static const char *const labels_{i}[] = "
                         + "{" + ", ".join(map(_c_string, s.labels)) + "};")
    lines.append("const struct mod_setting mod_settings[MOD_SETTING_COUNT] = {")
    text_at = 0
    for i, s in enumerate(settings):
        text = s.kind == "text"
        fields = [f".id = {s.id:#06x}", f".kind = MOD_KIND_{s.kind.upper()}",
                  f".when = MOD_WHEN_{s.when.upper()}", f".group = {names.index(s.group)}",
                  f".min = {s.min}", f".max = {s.max}",
                  f".def = {0 if text else s.default}", f".name = {_c_string(s.name)}"]
        if s.labels:
            fields.append(f".labels = labels_{i}")
        if text:
            fields += [f".text_default = {_c_string(s.default)}", f".text_at = {text_at}"]
            text_at += s.max + 1
        lines.append("    {" + ", ".join(fields) + "},")
    lines += ["};", "const char *const mod_groups[MOD_GROUP_COUNT] = {"
              + ", ".join(map(_c_string, names)) + "};", ""]
    return "\n".join(lines)


# The store: MODS, version, 0, entries length u16, entries {id u16, length u8, value},
# CRC-32 over everything before it, FF up to the end of the subsector.

def encode_value(setting, value):
    if setting.kind == "text":
        return value.encode("ascii")
    if setting.kind in ("flag", "enum"):
        return bytes([value])
    return struct.pack("<h", value)


def encode_store(entries):
    """A whole subsector from (id, value bytes) pairs."""
    body = b"".join(struct.pack("<HB", sid, len(v)) + v for sid, v in entries)
    data = STORE_MAGIC + bytes([STORE_VERSION, 0]) + struct.pack("<H", len(body)) + body
    data += struct.pack("<I", zlib.crc32(data))
    if len(data) > STORE_BYTES:
        raise ValueError(f"store of {len(data)} bytes does not fit in {STORE_BYTES}")
    return data + b"\xff" * (STORE_BYTES - len(data))


def decode_store(data):
    """[(id, value bytes)], or None for no store (bad magic, version, length or CRC)."""
    if len(data) < STORE_HEADER + 4 or data[:4] != STORE_MAGIC or data[4] != STORE_VERSION:
        return None
    n = struct.unpack_from("<H", data, 6)[0]
    end = STORE_HEADER + n
    if end + 4 > len(data) or struct.unpack_from("<I", data, end)[0] != zlib.crc32(data[:end]):
        return None
    out, at = [], STORE_HEADER
    while at + 3 <= end:
        sid, length = struct.unpack_from("<HB", data, at)
        if at + 3 + length > end:
            return None
        out.append((sid, data[at + 3:at + 3 + length]))
        at += 3 + length
    return out if at == end else None


def load(directory):
    path = Path(directory) / "overlay.toml"
    with path.open("rb") as f:
        t = tomllib.load(f)
    return from_toml(t.get("setting", []), Path(directory).resolve().name, path)


def main(argv):
    if len(argv) >= 1 and argv[0] == "list":
        settings = [s for d in argv[1:] for s in load(d)]
        check(settings)
        for s in settings:
            extra = f"labels {', '.join(s.labels)}" if s.labels else f"{s.min}..{s.max}"
            print(f"{s.id:#06x} {s.group}: {s.name} ({s.kind}, {s.when}, {extra}, "
                  f"default {s.default!r})")
        return 0
    if len(argv) >= 2 and argv[0] == "store":
        entries = []
        for arg in argv[2:]:
            sid, value = arg.split("=", 1)
            entries.append((int(sid, 0), struct.pack("<h", int(value, 0))))
        Path(argv[1]).write_bytes(encode_store(entries))
        return 0
    if len(argv) == 2 and argv[0] == "show":
        entries = decode_store(Path(argv[1]).read_bytes())
        if entries is None:
            print("no store (everything stock)")
        for sid, v in entries or []:
            print(f"{sid:#06x}: {v.hex(' ')}")
        return 0
    print(__doc__.strip(), file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
